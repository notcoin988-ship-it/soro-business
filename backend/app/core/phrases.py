"""Вежливые обороты: распознать и отрезать.

Отдельный модуль, потому что словарь нужен двоим и по разным поводам:

* `core/dialog.py` — ответить на «салом» без вопроса, не будя оператора;
* `core/rag.py` — ВЫРЕЗАТЬ приветствие из вопроса перед поиском.

Держать словарь в одном из них значило бы кольцевой импорт: `dialog`
зовёт `rag`, а `rag` понадобился бы `dialog`.

ЗАЧЕМ ВЫРЕЗАТЬ. Кросс-энкодер оценивает пару «вопрос — фрагмент» целиком,
и лишние слова, на которые фрагмент не отвечает, тянут оценку вниз.
Замер на боевой базе:

    «чигуна корти милли дархост кунам»          0,462  отвечает
    «салом чигуна корти милли дархост кунам»    0,048  эскалация
    «Салом! Чигуна корти милли дархост кунам?»  0,129  эскалация
    «Здравствуйте, как оформить карту…»         0,178  эскалация
    «Как оформить карту Корти Милли?»           0,379  отвечает

То есть одно «салом» роняет оценку в десять раз, а здороваться перед
вопросом — обычное дело для живого клиента. Найдено ручной проверкой.
"""

from __future__ import annotations

import re

GREETINGS = frozenset({
    "салом", "салом алейкум", "ассалом", "ассалому алейкум",
    "ассалому алайкум", "салам", "салом бародар",
    "привет", "приветствую", "здравствуйте", "здравствуй", "здрасте",
    "добрый день", "добрый вечер", "доброе утро",
    "hello", "hi", "hey", "start",
})
THANKS = frozenset({
    "раҳмат", "рахмат", "ташаккур", "сипос", "раҳмат калон",
    "спасибо", "спасибо большое", "благодарю", "мерси",
})
FAREWELL = frozenset({
    "хайр", "то дидор", "хуш омадед",
    "пока", "до свидания", "всего доброго", "спокойной ночи",
})

# Согласие: «да» на уточняющий вопрос бота. Смысла в себе не несёт —
# он весь в вопросе, на который отвечают, поэтому такие реплики
# разбираются отдельно (`core/context.offered_topic`), а не моделью:
# на «бале» она то переписывала реплику в тему, то возвращала как есть,
# и во втором случае клиент получал эскалацию на ровном месте.
AFFIRMATIONS = frozenset({
    "бале", "ҳа", "ха", "оре", "албатта", "хуб", "хуб аст",
    "да", "ага", "конечно", "хорошо", "давай", "давайте",
    "ok", "okay", "окей", "yes",
})

# Знаки препинания и эмодзи убираем: «Салом!!!» и «салом 😊» — то же самое.
NOT_WORD_RE = re.compile(r"[^\w\s]|_", re.UNICODE)

# Слово в исходном тексте. Обязано разбивать текст ровно так же, как
# `NOT_WORD_RE` (те же символы считаются разделителями, включая `_`), —
# на этом держится подсчёт слов в `strip_greeting`.
WORD_RE = re.compile(r"[^\W_]+", re.UNICODE)

# Обороты вежливости, которые тоже ничего не спрашивают. Отрезаются вместе
# с приветствием: «Салом! Подскажите, пожалуйста, ...» — три лишних слова.
FILLERS = frozenset({
    "подскажите", "скажите", "пожалуйста", "лутфан", "мархамат",
    "хотел спросить", "хотела спросить", "хочу спросить", "у меня вопрос",
})

# Самое длинное приветствие — три слова («ассалому алайкум бародар» и
# подобные). Больше трёх слов подряд не срезаем: рискуем откусить вопрос.
MAX_PREFIX_WORDS = 3


def normalize(text: str) -> str:
    """Сообщение без знаков препинания, в нижнем регистре, с одним пробелом."""
    words = NOT_WORD_RE.sub(" ", (text or "").lower())
    return " ".join(words.split())


def is_smalltalk(text: str) -> str | None:
    """Вежливость БЕЗ вопроса: 'greeting' | 'thanks' | 'farewell' | None.

    Сравниваем сообщение ЦЕЛИКОМ, а не по вхождению: «Салом! Фоизи амонат
    чанд аст?» — обычный вопрос, и перехватывать его нельзя.
    """
    words = normalize(text)
    if not words:
        return None
    if words in GREETINGS:
        return "greeting"
    if words in THANKS:
        return "thanks"
    if words in FAREWELL:
        return "farewell"
    return None


def is_affirmation(text: str) -> bool:
    """Согласие без содержания: «бале», «да», «хорошо».

    Сравниваем сообщение ЦЕЛИКОМ: «да, а сколько стоит?» — это вопрос, и
    подменять его темой из истории нельзя.
    """
    return normalize(text) in AFFIRMATIONS


# --- язык реплики ----------------------------------------------------------
#
# ЗАЧЕМ. Правило 2 промпта велит отвечать на языке вопроса, но промпт —
# просьба. Замер 14.08.2026, боевая модель, по 4 прогона на реплику:
#
#   «Какие документы нужны юридическому лицу…»  4 из 4 по-русски  ✔
#   «привет хочу оформить кредить»              4 из 4 ПО-ТАДЖИКСКИ
#   «хочу карту visa»                           по-таджикски
#
# Сначала грешили на фрагменты — мол, нашлось таджикское. Проверили: все
# три фрагмента в обоих случаях с русских страниц сайта. Дело в самой
# реплике: короткую, строчными и без вопросительного знака модель за
# русскую не считает и скатывается в язык системного промпта, а он
# начинается по-таджикски.
#
# Поэтому язык определяем сами и говорим модели прямым текстом.
#
# ПОЧЕМУ НЕ `rag.is_tajik`. Тот смотрит только на диакритику (ҳ, ӣ, ҷ) и
# в своей шапке честно предупреждает: для решений, влияющих на ответ
# клиенту, не годится. Таджикская реплика без диакритики — «чигуна корти
# милли дархост кунам» — туда не попадает вовсе.

# Буквы, которых в другом алфавите не бывает. Признак сильный, поэтому и
# весит больше слова. «ц» и «ь» не берём: они встречаются в таджикских
# заимствованиях и дали бы русский на ровном месте.
TAJIK_ONLY_LETTERS = frozenset("ҳӣҷӯқғ")
RUSSIAN_ONLY_LETTERS = frozenset("ыщъё")

# Служебные и самые частые предметные слова. Работают там, где буквы
# молчат: реплика без диакритики или короткая русская фраза.
TAJIK_WORDS = frozenset({
    "ман", "шумо", "мо", "аст", "ҳаст", "нест", "чанд", "чӣ", "чи", "ки",
    "дар", "аз", "ба", "бо", "барои", "оё", "ва", "ё", "мехоҳам",
    "мехоҳед", "метавонам", "метавонед", "кунам", "кунед", "гирам",
    "гиред", "маълумот", "бештар", "салом", "раҳмат", "бонк", "қарз",
    "корт", "пасандоз", "амонат", "ҳуҷҷат", "ҳуҷҷатҳо", "фоиз", "фоизи",
    "солона", "мӯҳлат", "чигуна", "дархост", "милли",
    # Приветствия и прощания: клиент часто пишет их ОДНИМ словом, и
    # другого сигнала в такой реплике нет вовсе. Без них «хайр» и
    # «ассалом» получали бы двуязычный ответ — то самое место, где
    # видно машину.
    "ассалом", "ташаккур", "сипос", "хайр", "дидор",
})
RUSSIAN_WORDS = frozenset({
    "я", "вы", "мы", "не", "это", "и", "в", "на", "для", "что", "как",
    "по", "или", "если", "можно", "нужно", "хочу", "хотел", "мне",
    "меня", "сколько", "какой", "какая", "какие", "где", "когда", "есть",
    "ли", "привет", "здравствуйте", "спасибо", "банк", "банка", "счёт",
    "счет", "карта", "карту", "карты", "кредит", "вклад", "депозит",
    "документы", "годовых", "открыть", "оформить", "получить", "ставка",
    # см. комментарий к таджикскому списку
    "здравствуй", "здрасте", "приветствую", "добрый", "доброе",
    "утро", "вечер", "пока", "свидания", "благодарю",
})

# Насколько уверенно должен победить язык. Единица — это «одно служебное
# слово перевесило»; ставим её, а не два: на репликах в три слова
# («хочу карту visa») больше просто не наберётся, а ошибиться здесь
# дешевле, чем промолчать — при `None` всё остаётся как было.
LANGUAGE_MARGIN = 1


def detect_language(text: str) -> str | None:
    """Язык реплики клиента: 'tg' | 'ru' | None.

    `None` — «не знаю»: смешанная реплика, одни цифры, латиница. Вызывающий
    тогда обязан вести себя как раньше, а не гадать: молчание здесь честнее
    неверной догадки, потому что ответ уедет клиенту.
    """
    words = [w.lower() for w in WORD_RE.findall(text or "")]
    letters = set((text or "").lower())

    tajik = 2 * len(TAJIK_ONLY_LETTERS & letters) + sum(
        word in TAJIK_WORDS for word in words
    )
    russian = 2 * len(RUSSIAN_ONLY_LETTERS & letters) + sum(
        word in RUSSIAN_WORDS for word in words
    )

    if tajik - russian >= LANGUAGE_MARGIN:
        return "tg"
    if russian - tajik >= LANGUAGE_MARGIN:
        return "ru"
    return None


def strip_greeting(text: str) -> str:
    """Убрать приветствие и вежливые обороты из НАЧАЛА вопроса.

    Только для поиска: модели вопрос уходит целиком, и здороваться в
    ответ она должна.

    Режем пословно с начала, пока слова складываются в известное
    приветствие или наполнитель. Если после этого ничего не осталось —
    возвращаем исходный текст: пустой запрос искать бессмысленно, а такой
    случай ловится раньше как smalltalk.

    ОСТАТОК ОТДАЁМ КУСКОМ ИСХОДНОГО ТЕКСТА, а не склейкой нормализованных
    слов. Разница не косметическая: та же мысль, записанная с «ёлочками»
    и без, даёт разную оценку, причём непредсказуемо в обе стороны. Замер
    на боевой базе, «как есть» против нормализованного:

        «Как оформить карту «Корти Милли»?»   0,320 → 0,481   +0,161
        «Фоизи амонат чанд аст?»              0,130 → 0,026   −0,104
        «Сколько стоит открытие счёта?»       0,423 → 0,482   +0,059

    Систематического выигрыша нет — это шум порядка ±0,1. Поэтому
    нормализация тут только служебная, для сравнения со словарём, и
    наружу не протекает: вопрос с приветствием обязан искаться ровно так
    же, как он же без приветствия.
    """
    original = text or ""
    words = normalize(original).split()
    if not words:
        return original

    cut = 0
    while cut < len(words):
        moved = False
        # сначала пробуем длинные сочетания: «ассалому алайкум» целиком
        for size in range(min(MAX_PREFIX_WORDS, len(words) - cut), 0, -1):
            phrase = " ".join(words[cut : cut + size])
            if phrase in GREETINGS or phrase in THANKS or phrase in FILLERS:
                cut += size
                moved = True
                break
        if not moved:
            break

    if cut == 0 or cut == len(words):
        return original

    # `normalize` бьёт текст ровно по этим же группам символов, поэтому
    # k-е слово нормализованной строки — это k-е совпадение здесь.
    starts = [m.start() for m in WORD_RE.finditer(original)]
    return original[starts[cut] :].strip()
