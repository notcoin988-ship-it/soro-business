"""История диалога: что помнить и как передавать (многоходовый диалог).

ОТВЕТСТВЕННОСТЬ: хранить предыдущие реплики в виде, пригодном и для
промпта модели, и для переписывания вопроса перед поиском. Ничего не
решает сам и наружу не ходит — из `core` берёт только `phrases` (словарь
вежливости), но не `llm` и не `rag`: их зовут `dialog` и `playground`,
которые импортируют и это. Иначе вышло бы кольцо.

ЗАЧЕМ. Раздел 6.6 велит боту «в конце, где уместно, задать один
уточняющий вопрос», и он его задаёт — а ответ на собственный вопрос
понять не мог. Живой прогон:

    Клиент:  салом чигуна корти милли дархост кунам
    Бот:     …Оё шумо аллакай барномаи «Эсхата Онлайн»-ро насб кардаед?
    Клиент:  не чи гуна насб кунам ?
    Бот:     Ин маълумот дар ҳуҷҷатҳои бонк нест — мутахассисро…

Ответ в базе есть (документ «Барномаи мобилии «Эсхата Онлайн»»), и поиск
даже ставил его ПЕРВЫМ — но оценка одинокой реплики «не чи гуна насб
кунам?» равна 0,002, потому что сама по себе она ни о чём. Раздел 9.3 ТЗ
требует, чтобы «Продолжить в Telegram» переносило контекст, — а контекста
не было нигде, ни в одном канале.

ПОЧЕМУ НЕ СКЛЕИТЬ ИСТОРИЮ С ВОПРОСОМ И НЕ ИСКАТЬ ЭТИМ. Пробовали, замер
на боевой базе — к реплике клиента приклеен уточняющий вопрос бота:

    | реплика клиента            | сама | +вопрос бота |
    |----------------------------|------|--------------|
    | не чи гуна насб кунам?     | 0,002|    0,599 ✔   |
    | обу ҳаво чӣ хел аст?       | 0,000|    0,429 ✘   |
    | баланси ман чанд аст?      | 0,001|    0,580 ✘   |
    | Дар Ориёнбонк фоизи қарз…? | 0,046|    0,633 ✘   |

Нужный случай чинится — и вместе с ним проходит всё подряд: погода,
чужой банк и запрос собственного баланса, который обязан уходить
оператору. Причина в природе кросс-энкодера: он оценивает пару целиком, а
вопрос бота порождён теми же фрагментами, по которым мы ищем, — оценка
получается круговой и порог перестаёт что-либо значить. Ещё нагляднее с
полным текстом ответа бота: 0,987 при заведомо НЕ том документе.

Поэтому историей вопрос ПЕРЕПИСЫВАЕТСЯ (`llm.condense_question`), а
ищется уже самостоятельная формулировка. Её оценка честная: «обу ҳаво чӣ
хел аст?» останется собой и уйдёт оператору, как и должно.

ЧТО ХРАНИМ. Только `text_masked`: инвариант проекта — оригинал живёт в
`messages.text` и до модели не доходит никогда. История уходит и в
промпт, и в чужой сервис, так что здесь это особенно важно.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from difflib import SequenceMatcher

from app.core import phrases

# Сколько реплик помним. Было 6 (три обмена) из соображения «дальше клиент
# обычно меняет тему». Замер на площадке 14.08.2026 показал, что три обмена
# кончаются раньше, чем разговор:
#
#   1. Какая ставка по срочному депозиту в сомони?  → «до 12% годовых»
#   2. А в долларах?                                → «2% годовых»
#   3. Какая минимальная сумма для открытия?        → «1000 сомони»
#   4. Какие документы нужны юрлицу для счёта?      → длинный ответ
#   5. Вернёмся к депозиту: какая там была ставка?  → ЭСКАЛАЦИЯ
#
# К пятому ходу первый обмен уже выброшен, и «там» не к чему привязать.
# Режет здесь именно счёт реплик, а не символы: в промпт на этом разговоре
# уходило 1077 символов из 1500, то есть потолок HISTORY_CHARS недобран.
# Он и остаётся настоящим ограничителем — раздуть промпт десять реплик не
# смогут, длинные всё равно не влезут в бюджет.
HISTORY_TURNS = 10

# Потолок в символах поверх счёта реплик: один ответ бота бывает длинным,
# и шесть таких раздувают промпт сильнее, чем весь блок <docs>.
HISTORY_CHARS = 1500

# Ссылки [1] и знаки препинания — общий инструмент двух мест ниже:
# `offered_topic` чистит от них запрос, `is_repeat` — сравниваемый текст.
_CITE_RE = re.compile(r"\[[\d.,;\s]+\]")
_NOT_WORD_RE = re.compile(r"[^\w\s]|_", re.UNICODE)


@dataclass(frozen=True)
class Turn:
    """Одна реплика. `role` — 'user' или 'assistant', как в chat API."""

    role: str
    text: str
    # Фрагменты, на которых построен ответ бота. У реплик клиента пусто.
    # Нужны согласию: «бале» на «хотите узнать больше?» означает БОЛЬШЕ,
    # и эти чанки из следующего поиска исключаются.
    chunks: tuple[int, ...] = ()


def trim(turns: list[Turn]) -> list[Turn]:
    """Последние реплики в пределах обоих бюджетов.

    Режем с конца: свежие важнее. Реплику целиком не влезающую — не
    обрезаем посередине, а выбрасываем: полфразы в промпте хуже, чем её
    отсутствие.
    """
    kept: list[Turn] = []
    budget = HISTORY_CHARS
    for turn in reversed(turns[-HISTORY_TURNS:]):
        text = (turn.text or "").strip()
        if not text or len(text) > budget:
            continue
        kept.append(Turn(turn.role, text, turn.chunks))
        budget -= len(text)
    kept.reverse()
    return kept


def as_dialogue(turns: list[Turn], question: str) -> str:
    """История и новая реплика одним текстом — для переписывания вопроса.

    Обычным текстом, а не ролями chat API: модель здесь не отвечает
    клиенту, а разбирает расшифровку разговора, и «Клиент:» / «Бот:»
    читается ей однозначнее, чем чередование ролей.

    ПОСЛЕДНЯЯ СТРОКА — ЗАДАНИЕ, А НЕ РЕПЛИКА. Первая версия заканчивала
    текст на «Клиент: …», и модель дописывала разговор дальше: вместо
    переформулировки приходил ответ клиенту, который уходил прямо в
    поиск (замер — в комментарии к `CONDENSE_SYSTEM`). Явная пометка
    «Реплика для переписывания» убирает этот соблазн.
    """
    # Ссылки из прошлых ответов бота убираем: для переписывателя это шум,
    # и один раз «[1]» уже уехало прямо в поисковый запрос —
    # «…маълумоти бештар гиред? [1]».
    lines = ["История разговора:"]
    lines += [
        "{}: {}".format(
            "Клиент" if turn.role == "user" else "Бот",
            turn.text if turn.role == "user" else _CITE_RE.sub("", turn.text).strip(),
        )
        for turn in trim(turns)
    ]
    lines.append("")
    lines.append(f"Реплика для переписывания: {question}")
    return "\n".join(lines)


def offered_topic(turns: list[Turn]) -> str:
    """Тема, которую бот предложил последним уточняющим вопросом.

    Нужна для согласия: «бале» само по себе не значит ничего, весь смысл
    в вопросе, на который отвечают. Берём ПОСЛЕДНЕЕ вопросительное
    предложение бота — именно на него отвечает клиент.

    ПОЧЕМУ НЕ ОТДАЁМ ЭТО МОДЕЛИ. Отдавали. На «бале» она то переписывала
    реплику в тему, то возвращала как есть по правилу 4 («понятно без
    истории»), и во втором случае поиск шёл по слову «бале» — оценка
    0,001 и эскалация на ровном месте. Здесь же ответ однозначен, и
    гадать незачем.

    Возвращает пустую строку, если бот ничего не спрашивал.
    """
    last = next((t.text for t in reversed(turns) if t.role == "assistant"), "")
    # Ссылки [1] в запрос не нужны: для поиска это мусор. Один раз они
    # уже уехали в переписанный вопрос целиком — «…маълумоти бештар
    # гиред? [1]».
    last = _CITE_RE.sub(" ", last or "")
    if "?" not in last:
        return ""

    # всё до последнего «?» — там же и конец нужного предложения
    head = last.rsplit("?", 1)[0]
    # отрезаем предыдущие предложения, иначе в запрос уедет весь абзац
    for separator in (".", "!", "?", "\n"):
        head = head.rsplit(separator, 1)[-1]
    return " ".join(head.split())


def used_chunks(turns: list[Turn]) -> list[int]:
    """Фрагменты последнего ответа бота — то, что клиент уже прочитал."""
    return list(
        next((t.chunks for t in reversed(turns) if t.role == "assistant"), ())
    )


# --- повтор ответа ---------------------------------------------------------
#
# Правило 7 промпта велит боту задать уточняющий вопрос, клиент отвечает
# «бале» — и модель выдаёт ТОТ ЖЕ абзац слово в слово. Живой прогон, три
# реплики подряд:
#
#   Клиент: бале  → «Хуб, пас шумо метавонед кортро дар барномаи…»
#   Клиент: бале  → «Хуб, пас шумо метавонед кортро дар барномаи…»  (тот же)
#
# Она видит свой прошлый ответ в истории и, не найдя во фрагментах нового,
# пересказывает его. Правило 8 промпта просит так не делать, но промпт —
# просьба; здесь механическая проверка.

# ПОЧЕМУ ДВЕ МЕРЫ, А НЕ ОДНА. Сначала стояло одно посимвольное сравнение
# с порогом 0,9 — и живой прогон его обошёл: модель не повторила ответ
# дословно, а ПЕРЕСКАЗАЛА. «…онро дар шуъбаҳои бонк бо пешниҳоди
# шиноснома фармоиш диҳед» стало «…ба яке аз шуъбаҳои бонк ташриф
# оварда, шиносномаи худро пешниҳод намоед» — то же самое другими
# словами, сходство 0,804 и мимо порога.
#
# Замер на четырёх парах:
#
#   пара                        посимвольно   Жаккар
#   пересказ (ловить обязаны)       0,804      0,646
#   новый ответ про установку       0,104      0,133
#   совсем другая тема              0,157      0,043
#   короткий новый факт             0,085      0,000
#
# Разрыв велик у обеих мер, но ловят они разное: посимвольная — правку по
# живому, Жаккар — пересказ теми же словами в другом порядке. Берём обе,
# срабатываем по любой, пороги ставим посреди разрыва.
REPEAT_RATIO = 0.8

# Доля общих слов: пересечение к объединению. Именно Жаккар, а не «доля
# слов короткого текста»: иначе короткий новый факт, все слова которого
# встречались в длинном прошлом ответе, дал бы единицу и был бы объявлен
# повтором.
REPEAT_JACCARD = 0.5

# Короткие ответы сравнивать бессмысленно: «Бале.» и «Хайр.» дадут
# высокое сходство, не будучи повтором по существу.
REPEAT_MIN_CHARS = 80



def _flatten(text: str) -> str:
    """Текст без ссылок, знаков и регистра — для сравнения по существу."""
    return " ".join(_NOT_WORD_RE.sub(" ", _CITE_RE.sub(" ", text or "").lower()).split())


def is_repeat(answer: str, turns: list[Turn], question: str) -> bool:
    """Повторяет ли ответ то, что бот уже говорил в этом разговоре.

    ВАЖНОЕ ИСКЛЮЧЕНИЕ: если клиент задал ТОТ ЖЕ вопрос, повтор ответа —
    правильное поведение, а не поломка. Человек мог не дочитать или
    вернуться к разговору позже, и отвечать ему «я уже говорил» было бы
    хамством. Поэтому сравниваем ещё и вопросы.

    НО НЕ ДЛЯ СОГЛАСИЯ. Два «бале» подряд — это не «тот же вопрос»: во
    второй раз клиент соглашается на НОВОЕ предложение бота. Первая
    версия исключения этого не различала, и живой прогон дал четыре
    одинаковых ответа подряд — ровно ту поломку, ради которой всё
    писалось.
    """
    flat = _flatten(answer)
    if len(flat) < REPEAT_MIN_CHARS:
        return False

    last_question = next(
        (t.text for t in reversed(turns) if t.role == "user"), ""
    )
    if not phrases.is_affirmation(question) and _flatten(question) == _flatten(
        last_question
    ):
        return False

    return any(
        SequenceMatcher(None, flat, _flatten(turn.text)).ratio() >= REPEAT_RATIO
        for turn in turns
        if turn.role == "assistant"
    )
