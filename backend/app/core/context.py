"""История диалога: что помнить и как передавать (многоходовый диалог).

ОТВЕТСТВЕННОСТЬ: хранить предыдущие реплики в виде, пригодном и для
промпта модели, и для переписывания вопроса перед поиском. Ничего не
решает сам и наружу не ходит — поэтому модуль чистый, без импорта `llm`
и `rag`: их зовут `dialog` и `playground`, которые импортируют и это.

ЗАЧЕМ. Раздел 6.6 велит боту «в конце, где уместно, задать один
уточняющий вопрос», и он его задаёт — а ответ на собственный вопрос
понять не мог. Живой прогон:

    Клиент:  салом чигуна корти милли дархост кунам
    Бот:     …Оё шумо аллакай барномаи «Эсхата Онлайн»-ро насб кардаед?
    Клиент:  не чи гуна насб кунам ?
    Бот:     Ин маълумот дар ҳуҷҷатҳои бонк нест — мутахассисро…

Ответ в базе есть (документ «Барномаи мобилии «Эсхата Онлайн»»), и поиск
даже ставил его ПЕРВЫМ — но оценка одинокой реплики «не чи гуна насб
кунам?» равна 0,002, потому что сама по себе она ни о чём. Раздел 9.3 ТЗ
требует, чтобы «Продолжить в Telegram» переносило контекст, — а контекста
не было нигде, ни в одном канале.

ПОЧЕМУ НЕ СКЛЕИТЬ ИСТОРИЮ С ВОПРОСОМ И НЕ ИСКАТЬ ЭТИМ. Пробовали, замер
на боевой базе — к реплике клиента приклеен уточняющий вопрос бота:

    | реплика клиента            | сама | +вопрос бота |
    |----------------------------|------|--------------|
    | не чи гуна насб кунам?     | 0,002|    0,599 ✔   |
    | обу ҳаво чӣ хел аст?       | 0,000|    0,429 ✘   |
    | баланси ман чанд аст?      | 0,001|    0,580 ✘   |
    | Дар Ориёнбонк фоизи қарз…? | 0,046|    0,633 ✘   |

Нужный случай чинится — и вместе с ним проходит всё подряд: погода,
чужой банк и запрос собственного баланса, который обязан уходить
оператору. Причина в природе кросс-энкодера: он оценивает пару целиком, а
вопрос бота порождён теми же фрагментами, по которым мы ищем, — оценка
получается круговой и порог перестаёт что-либо значить. Ещё нагляднее с
полным текстом ответа бота: 0,987 при заведомо НЕ том документе.

Поэтому историей вопрос ПЕРЕПИСЫВАЕТСЯ (`llm.condense_question`), а
ищется уже самостоятельная формулировка. Её оценка честная: «обу ҳаво чӣ
хел аст?» останется собой и уйдёт оператору, как и должно.

ЧТО ХРАНИМ. Только `text_masked`: инвариант проекта — оригинал живёт в
`messages.text` и до модели не доходит никогда. История уходит и в
промпт, и в чужой сервис, так что здесь это особенно важно.
"""

from __future__ import annotations

from dataclasses import dataclass

# Сколько реплик помним. Три обмена — этого хватает на «а сколько стоит?»
# и «а какой минимальный взнос?», а дальше клиент обычно меняет тему.
# Больше — дороже промпт и выше шанс, что модель уцепится за старую тему.
HISTORY_TURNS = 6

# Потолок в символах поверх счёта реплик: один ответ бота бывает длинным,
# и шесть таких раздувают промпт сильнее, чем весь блок <docs>.
HISTORY_CHARS = 1500


@dataclass(frozen=True)
class Turn:
    """Одна реплика. `role` — 'user' или 'assistant', как в chat API."""

    role: str
    text: str


def trim(turns: list[Turn]) -> list[Turn]:
    """Последние реплики в пределах обоих бюджетов.

    Режем с конца: свежие важнее. Реплику целиком не влезающую — не
    обрезаем посередине, а выбрасываем: полфразы в промпте хуже, чем её
    отсутствие.
    """
    kept: list[Turn] = []
    budget = HISTORY_CHARS
    for turn in reversed(turns[-HISTORY_TURNS:]):
        text = (turn.text or "").strip()
        if not text or len(text) > budget:
            continue
        kept.append(Turn(turn.role, text))
        budget -= len(text)
    kept.reverse()
    return kept


def as_dialogue(turns: list[Turn], question: str) -> str:
    """История и новая реплика одним текстом — для переписывания вопроса.

    Обычным текстом, а не ролями chat API: модель здесь не отвечает
    клиенту, а разбирает расшифровку разговора, и «Клиент:» / «Бот:»
    читается ей однозначнее, чем чередование ролей.

    ПОСЛЕДНЯЯ СТРОКА — ЗАДАНИЕ, А НЕ РЕПЛИКА. Первая версия заканчивала
    текст на «Клиент: …», и модель дописывала разговор дальше: вместо
    переформулировки приходил ответ клиенту, который уходил прямо в
    поиск (замер — в комментарии к `CONDENSE_SYSTEM`). Явная пометка
    «Реплика для переписывания» убирает этот соблазн.
    """
    lines = ["История разговора:"]
    lines += [
        f"{'Клиент' if turn.role == 'user' else 'Бот'}: {turn.text}"
        for turn in trim(turns)
    ]
    lines.append("")
    lines.append(f"Реплика для переписывания: {question}")
    return "\n".join(lines)
