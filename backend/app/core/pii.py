"""Маскирование ПДн (раздел 8.2 ТЗ). Вызывается ДО модели, всегда.

Код паттернов приведён дословно по ТЗ. Порядок применения важен:
карты раньше телефонов, иначе телефон «съест» часть номера карты.

В messages.text хранится оригинал (оператор должен видеть настоящий номер),
в messages.text_masked — маска; в модель уходит ТОЛЬКО text_masked.
"""

import re

PATTERNS = [
    # карты: 16 цифр с пробелами/дефисами или слитно
    (re.compile(r"\b(?:\d[ -]?){13,19}\b"), "[CARD]"),
    # телефоны Таджикистана: +992 xx xxx xx xx и вариации
    (re.compile(r"(?:\+?992[\s-]?)?\d{2}[\s-]?\d{3}[\s-]?"
                r"\d{2}[\s-]?\d{2}\b"), "[PHONE]"),
    # паспорт РТ: серия A + 8 цифр (латиница или кириллица А)
    (re.compile(r"\b[AА]\s?\d{8}\b", re.I), "[PASSPORT]"),
    # ИНН 9 цифр
    (re.compile(r"\b\d{9}\b"), "[INN]"),
]


def mask(text: str) -> str:
    for rx, repl in PATTERNS:
        text = rx.sub(repl, text)
    return text
