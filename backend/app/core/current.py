"""Какой воркспейс обслуживает текущий запрос.

ЗАЧЕМ. До сих пор воркспейс был один и брался из `.env`: демо-стенд
показывали одному банку. Как только в консоли появилась кнопка «Добавить
банк», понадобился способ сказать бэкенду, чей именно экран открыт.

ПОЧЕМУ CONTEXTVAR, А НЕ ПАРАМЕТР В КАЖДОЙ РУЧКЕ. Воркспейс нужен
буквально везде: документы, диалоги, аналитика, обзор, каналы, инбокс —
два десятка эндпоинтов, и все они уже зовут `dialog.get_workspace`.
Протаскивать slug через каждую подпись значит переписать их все и не
забыть ни одной; забытая ручка молча покажет чужой банк. Здесь же выбор
живёт ровно в одном месте — в заголовке `X-Workspace`, который ставит
middleware.

ContextVar, а не глобальная переменная: у каждого запроса свой контекст,
и параллельные запросы двух вкладок не перепутаются.

КАНАЛЫ СЮДА НЕ ХОДЯТ. Telegram и виджет присылают воркспейс сами (`ws` в
теле или в query) либо работают с воркспейсом по умолчанию: заголовка от
них не бывает, и подставлять им «последний выбранный в консоли» нельзя —
клиент банка не должен зависеть от того, какую вкладку открыл оператор.
"""

from __future__ import annotations

from contextvars import ContextVar

HEADER = "X-Workspace"

_current: ContextVar[str | None] = ContextVar("current_workspace", default=None)


def set_slug(slug: str | None) -> None:
    _current.set(slug or None)


def slug() -> str | None:
    """Воркспейс текущего запроса или `None`, если его не выбирали."""
    return _current.get()
