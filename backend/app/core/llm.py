# --- промпт раздела 6.6 ---------------------------------------------------
#
# Оригинал ТЗ оставлен рядом НЕ для истории: по нему сверяется, что мы
# поменяли ровно три места и ничего не потеряли. Раздел 6.6 велит брать
# промпт дословно, отход согласован с тимлидом после живого прогона.
#
# ЧТО ПОКАЗАЛ ПРОГОН боевой модели (5 запусков одного вопроса):
#   * в 4 случаях из 5 модель отвечала по документам и ВСЁ РАВНО
#     дописывала [ESCALATE] — диалог уходил оператору на исправном
#     ответе, а в консоли загоралось «Передан оператору»;
#   * раз в несколько запусков вместо [1] появлялось [1.2] — модель
#     путала номер фрагмента с номером пункта тарифа, ссылка не
#     распознавалась и бейдж не рисовался;
#   * в текст попадали служебные пометки вроде [Уточняющий вопрос].
#
# Правки — в правилах 1, 3 и 7, по одной на каждую находку. Остальное
# слово в слово как в ТЗ.

