"""Тесты маскирования ПДн (раздел 8.2 ТЗ: «тесты обязательны»).

ТЗ требует 10 примеров. Набор расширен до сотни, потому что десять примеров
проверяют ровно те случаи, на которые паттерны и рассчитаны, — а продукт
банковский, и цена пропуска здесь выше цены лишнего теста.

История набора. Первая версия ловила 26 дефектов в паттернах раздела 8.2 —
они были помечены ``xfail(strict=True)`` и ждали решения по ТЗ. Решение
принято: паттерны переписаны (см. `core/pii.py` и `report.md`, п. 23),
пометки сняты, весь набор зелёный. Строгий xfail отработал ровно так, как
задумывался: молча «починить» дефект было нельзя — набор сам потребовал
снять пометку.

Проверяется два утверждения на случай:
  1. исходные данные исчезли из строки (``secret not in out``);
  2. на их месте стоит правильная метка.

Первое важнее: частично замаскированная строка выглядит обработанной, но
данные в ней остаются, и глазами в инбоксе этого не заметить.
"""

