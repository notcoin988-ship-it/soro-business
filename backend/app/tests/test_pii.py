IDEMPOTENT_CASES = [
    "Корт 5058123456789012",
    "Телефон +992931234567",
    "Паспорт A12345678",
    "Корт 5058123456789012, телефон 931234567",
    "Салом, фоизи амонат чанд аст?",
]


@pytest.mark.parametrize("src", IDEMPOTENT_CASES)
def test_mask_is_idempotent(src):
    """Повторное маскирование не должно ничего менять.

    Важно потому, что text_masked может пройти через mask() второй раз —
    например, при пересылке сообщения оператору или в аудит.
    """
    once = mask(src)
    assert mask(once) == once


def test_mask_returns_str():
    assert isinstance(mask("Корт 5058123456789012"), str)


def test_mask_does_not_mutate_input():
    src = "Корт 5058123456789012"
    mask(src)
    assert src == "Корт 5058123456789012"


def test_empty_string():
    assert mask("") == ""
