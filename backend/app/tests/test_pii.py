@pytest.mark.parametrize("src,secret", ACCOUNT_CASES)
@pytest.mark.xfail(
    reason="Ни номера счёта (20 цифр), ни IBAN в паттернах раздела 8.2 нет. "
           "Совпадают лишь обрывки чужими паттернами: 'Ҳисоб 20206972000[PHONE]' "
           "— первые 11 цифр счёта остаются в открытом виде. Строка выглядит "
           "обработанной, но данные в ней есть.",
    strict=True,
)
def test_account_number_is_masked(src, secret):
    out = mask(src)
    # проверка «полной строки нет в выводе» здесь бесполезна: при частичном
    # маскировании она проходит, а цифры остаются. Требуем, чтобы от номера
