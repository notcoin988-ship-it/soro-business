"""Тесты маскирования ПДн (раздел 8.2 ТЗ: «тесты обязательны»).

ТЗ требует 10 примеров. Набор расширен до сотни, потому что десять примеров
проверяют ровно те случаи, на которые паттерны и рассчитаны, — а продукт
банковский, и цена пропуска здесь выше цены лишнего теста.

Как читать результат:

* **passed** — модуль ведёт себя так, как задумано в ТЗ.
* **xfailed** — известный дефект, зафиксированный документально. Все они
  перечислены в NOTES-otkloneniya.md, пункт 2, и ждут решения тимлида.

У всех xfail стоит ``strict=True``: когда паттерны поправят, тест начнёт
проходить, и pytest сообщит об этом как об ошибке XPASS(strict). То есть
исправление нельзя внести молча — набор сам потребует снять пометку.

Проверяется два утверждения на случай:
  1. исходные данные исчезли из строки (``secret not in out``);
  2. на их месте стоит правильная метка.

Первое важнее: частично замаскированная строка выглядит обработанной, но
данные в ней остаются, и глазами в инбоксе этого не заметить.
"""

import re

import pytest

from app.core.pii import mask

X = pytest.mark.xfail

# ---------------------------------------------------------------------------
# Банковские карты — ожидаем [CARD] и полное исчезновение номера
# ---------------------------------------------------------------------------

CARD_CASES = [
    ("Корти ман 5058123456789012", "5058123456789012"),
    ("Корт 5058 1234 5678 9012", "5058 1234 5678 9012"),
    ("Корт 5058-1234-5678-9012", "5058-1234-5678-9012"),
    ("Карта 4278380012345678 заблокирована", "4278380012345678"),
    ("Спишите с карты 4278 3800 1234 5678", "4278 3800 1234 5678"),
    ("5058123456789012", "5058123456789012"),
    ("Рақами корт: 5058123456789012.", "5058123456789012"),
    ("(5058123456789012)", "5058123456789012"),
    ("Корт 1234567890123", "1234567890123"),
    ("Корт 1234567890123456789", "1234567890123456789"),
    ("Корт 5058-1234 5678-9012", "5058-1234 5678-9012"),
    ("Мастеркард 5375 4111 1111 1111", "5375 4111 1111 1111"),
    ("Visa 4111111111111111 кор намекунад", "4111111111111111"),
    ("корт№5058123456789012", "5058123456789012"),
    ("Корти ман — 5058 1234 5678 9012, лутфан санҷед", "5058 1234 5678 9012"),
    ("0000000000000000", "0000000000000000"),
    ("5058-1234-5678-9012.", "5058-1234-5678-9012"),
    pytest.param(
        "Корт 5058.1234.5678.9012", "5058.1234.5678.9012",
        marks=X(reason="Разделитель «точка» в паттерне карты не предусмотрен — "
                       "разрешены только пробел и дефис. Номер проходит целиком.",
                strict=True),
    ),
    pytest.param(
        "корти5058123456789012ман", "5058123456789012",
        marks=X(reason="\\b не срабатывает между кириллической буквой и цифрой, "
                       "поэтому карта, вписанная без пробелов внутрь слова, "
                       "не маскируется вообще.",
                strict=True),
    ),
    pytest.param(
        "Корт 5058  1234  5678  9012", "5058  1234  5678  9012",
        marks=X(reason="Паттерн допускает ровно один пробел между группами. "
                       "Двойной пробел — и номер проходит целиком.",
                strict=True),
    ),
    pytest.param(
        "5058\t1234\t5678\t9012", "5058\t1234\t5678\t9012",
        marks=X(reason="Табуляция как разделитель не предусмотрена. "
                       "Встречается при копировании из таблиц.",
                strict=True),
    ),
]


@pytest.mark.parametrize("src,secret", CARD_CASES)
def test_card_is_masked(src, secret):
    out = mask(src)
    assert secret not in out, f"номер карты остался в тексте: {out!r}"
    assert "[CARD]" in out, f"метка [CARD] не поставлена: {out!r}"


