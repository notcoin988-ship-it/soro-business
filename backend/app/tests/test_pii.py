MIXED_CASES = [
    ("Корт 5058123456789012, телефон 931234567", ["5058123456789012", "931234567"]),
    ("Паспорт A12345678 и ИНН 987654321", ["A12345678", "987654321"]),
    ("Салом! Корти ман 5058 1234 5678 9012 кор намекунад", ["5058 1234 5678 9012"]),
    ("Занг ба +992931234567, корт 4278380012345678",
     ["+992931234567", "4278380012345678"]),
    ("Шиноснома А12345678, рақам 931234567, корт 5058123456789012",
     ["А12345678", "931234567", "5058123456789012"]),
    ("Ману Далер, корти ман 5058123456789012, маблағ 500 сомонӣ",
     ["5058123456789012"]),
    ("Корт 5058123456789012 ва сана 03.08.2026", ["5058123456789012"]),
    ("Ду корт: 5058123456789012 ва 4278380012345678",
     ["5058123456789012", "4278380012345678"]),
    ("Ду рақам: 931234567 ва 987654321", ["931234567", "987654321"]),
    ("5058123456789012 5058123456789012", ["5058123456789012"]),
    pytest.param(
        "Телефон 931234567 ва ҳисоб 20206972000123456789",
        ["931234567", "20206972000123456789"],
        marks=X(reason="Телефон замаскирован, а из номера счёта остаются "
                       "первые 11 цифр: 'ҳисоб 20206972000[PHONE]'.",
                strict=True),
    ),
]


@pytest.mark.parametrize("src,secrets", MIXED_CASES)
def test_all_pii_removed_from_message(src, secrets):
    out = mask(src)
    for s in secrets:
        assert s not in out, f"в тексте осталось {s!r}: {out!r}"
    # плюс защита от частичного маскирования: длинных цепочек цифр остаться
    # не должно. Порог 5 — чтобы не цеплять годы (2026) и суммы (500)
    leftover = re.search(r"\d{5,}", out)
    assert not leftover, f"остался фрагмент ПДн {leftover.group()!r}: {out!r}"


