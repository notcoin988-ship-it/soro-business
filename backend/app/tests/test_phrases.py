"""Вежливые обороты: распознать и отрезать (`core/phrases.py`).

Модуль крошечный, но ошибка в нём стоит дорого в обе стороны: отрежем
лишнее — потеряем вопрос, не отрежем — уроним поиск. Живой замер, ради
которого он написан, приведён в докстроке самого модуля.
"""

from __future__ import annotations

import pytest

from app.core.phrases import (
    detect_language,
    is_smalltalk,
    normalize,
    strip_greeting,
)

# ---------------------------------------------------------------------------
# вежливость без вопроса
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "text, kind",
    [
        ("салом", "greeting"),
        ("Салом!", "greeting"),
        ("  ЗДРАВСТВУЙТЕ  ", "greeting"),
        ("hi", "greeting"),
        ("раҳмат", "thanks"),
        ("Спасибо большое!", "thanks"),
        ("хайр", "farewell"),
        ("До свидания.", "farewell"),
    ],
)
def test_smalltalk_kinds(text, kind):
    assert is_smalltalk(text) == kind


@pytest.mark.parametrize(
    "text",
    [
        "Салом! Фоизи амонат чанд аст?",
        "Здравствуйте, как оформить карту?",
        "",
        "   ",
        "😊",
    ],
)
def test_not_smalltalk(text):
    """Вопрос с приветствием — это ВОПРОС.

    Сравнение идёт по сообщению целиком: проверка по вхождению
    перехватывала бы каждый вежливый вопрос и бот отвечал бы «Салом!»
    вместо ответа.
    """
    assert is_smalltalk(text) is None


def test_normalize_strips_punctuation_and_case():
    assert normalize("  Салом!!!  😊 ") == "салом"


# ---------------------------------------------------------------------------
# срезание приветствия перед поиском
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    "question, expected",
    [
        # тот самый случай из ручной проверки: «салом» роняло оценку с
        # 0,462 до 0,048 — в десять раз, мимо порога
        (
            "салом чигуна корти милли дархост кунам",
            "чигуна корти милли дархост кунам",
        ),
        (
            "Салом! Чигуна корти милли дархост кунам?",
            "Чигуна корти милли дархост кунам?",
        ),
        (
            "Здравствуйте, как оформить карту Корти Милли?",
            "как оформить карту Корти Милли?",
        ),
        # наполнители режутся вместе с приветствием
        (
            "Салом! Подскажите, пожалуйста, комиссия за перевод",
            "комиссия за перевод",
        ),
        ("Ассалому алейкум, фоизи амонат чанд аст", "фоизи амонат чанд аст"),
    ],
)
def test_greeting_prefix_is_cut(question, expected):
    assert strip_greeting(question) == expected


def test_remainder_keeps_original_spelling():
    """Остаток — кусок ИСХОДНОГО текста: регистр, «ёлочки», знак вопроса.

    Иначе вопрос с приветствием и он же без приветствия ушли бы в поиск
    разными строками и получили разные оценки — расхождение до 0,16 по
    шкале переранкера (замер в докстроке `strip_greeting`).
    """
    plain = "Фоизи амонати «Ояндасоз» чанд аст?"

    assert strip_greeting(f"Салом! {plain}") == plain
    assert strip_greeting(plain) == plain


@pytest.mark.parametrize(
    "question",
    [
        "чигуна корти милли дархост кунам",
        "Как оформить карту Корти Милли?",
        "комиссия за перевод в другой банк",
    ],
)
def test_question_without_greeting_is_untouched(question):
    """Без приветствия текст возвращается КАК ЕСТЬ, вместе с регистром и
    знаками: нормализация нужна только там, где мы что-то отрезали."""
    assert strip_greeting(question) == question


@pytest.mark.parametrize("question", ["салом", "Салом!", "спасибо", ""])
def test_nothing_left_returns_original(question):
    """Если после среза не остаётся ничего — отдаём исходный текст.

    Пустой запрос искать бессмысленно, а такое сообщение ловится раньше
    как smalltalk и до поиска не доходит вовсе.
    """
    assert strip_greeting(question) == question


def test_greeting_inside_question_is_kept():
    """Режем только НАЧАЛО. «Как ответить на салом клиента» — вопрос про
    слово «салом», и выкусывать его из середины нельзя."""
    question = "как правильно ответить на салом клиента"
    assert strip_greeting(question) == question


def test_long_prefix_is_not_over_cut():
    """Сторож границы MAX_PREFIX_WORDS: подряд идущие обычные слова не
    должны съедаться, даже если начались с приветствия."""
    assert strip_greeting("салом карта карта карта") == "карта карта карта"


