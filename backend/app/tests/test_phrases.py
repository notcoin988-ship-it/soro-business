@pytest.mark.parametrize(
    "text, language",
    [
        # короткие и неряшливые — те самые, на которых модель уезжала
        # в таджикский, хотя клиент писал по-русски
        ("привет хочу оформить кредить", "ru"),
        ("хочу карту visa", "ru"),
        ("здравствуйте как открыть вклад", "ru"),
        ("Какие документы нужны юридическому лицу для открытия счёта?", "ru"),
        ("А в долларах?", "ru"),
        # таджикский с диакритикой и без неё — второй случай важнее,
        # именно его не видит `rag.is_tajik`
        ("Фоизи амонати «Озод» чанд фоиз аст?", "tg"),
        ("Салом, ман мехоҳам қарз гирам", "tg"),
        ("чигуна корти милли дархост кунам", "tg"),
        ("не чи гуна насб кунам ?", "tg"),
    ],
)
def test_detect_language(text, language):
    assert detect_language(text) == language


@pytest.mark.parametrize("text", ["visa", "12345", "ok", "", "👍"])
def test_language_unknown_is_none(text):
    """Гадать нельзя: на `None` вызывающий обязан вести себя как раньше.

    Латиница, цифры и эмодзи не говорят о языке клиента ничего, а неверный
    приказ о языке уедет клиенту в ответе.
    """
    assert detect_language(text) is None
