// СЦЕНАРИЙ KILLER DEMO — 10 шагов за 2–3 минуты.
//
// ЗАЧЕМ ОН ОТДЕЛЬНЫМ ФАЙЛОМ. Презентатор не должен вводить руками ни одного
// символа: на встрече любая опечатка в поле ввода ломает ритм, а
// живой запрос к модели может ответить за 7 секунд вместо одной. Поэтому
// реплики, тайминги и подписи зафиксированы здесь, и прогон повторяется
// одинаково — на репетиции и на встрече.
//
// СВЯЗНОСТЬ. Цифры шагов 06–09 берутся из `intel.ts`: то, что демо называет
// вслух, обязано совпадать с дашбордом и отчётом, которые заказчик откроет
// сразу после показа. Расхождение здесь стоит дороже любой недоделки.
//
// ЧЕСТНОСТЬ. Диалог клиента — вымышленный, персональных данных в нём нет
// (правило 25 задания). Шаг 03 намеренно показывает вопрос, на который
// система отвечать НЕ должна: демо продаёт не всезнание, а границу.

