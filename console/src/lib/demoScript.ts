export type StepKind =
  | "chat"
  | "escalation"
  | "operator"
  | "analytics"
  | "insight"
  | "recommendation"
  | "report"
  | "final";

export interface Fragment {
  title: string;
  page: string;
  passage: string;
  score: number;
}

export interface DemoStep {
  id: string;
  /** Номер в полосе прогресса. */
  num: string;
  /** Короткая подпись в полосе прогресса. */
  chip: string;
  kind: StepKind;
  /** Одна фраза для зрителя — что сейчас происходит. */
  caption: string;
  /** Сколько шаг живёт в автоматическом режиме, мс. */
  duration: number;

  // --- поля, зависящие от вида шага ---
  channel?: string;
  question?: string;
  intent?: string;
  language?: string;
  confidence?: number;
  answer?: string;
  fragments?: Fragment[];
  warning?: string;
  operator?: OperatorContext;
  analytics?: AnalyticsBlock;
  insight?: InsightBlock;
  recommendation?: RecommendationBlock;
  report?: ReportBlock;
}

export interface OperatorContext {
  customer: string;
  channel: string;
  reason: string;
  summary: string;
  intent: string;
  confidence: number;
  history: { from: "client" | "bot" | "operator"; text: string; at: string }[];
  suggested: string;
  nextAction: string;
  sources: string[];
}

export interface AnalyticsBlock {
  headline: string;
  analyzed: string;
  findings: { kind: "warn" | "new" | "ok"; text: string }[];
}

export interface InsightBlock {
  headline: string;
  what: string;
  why: string;
  impact: string;
  evidence: string[];
  confidence: number;
}

export interface RecommendationBlock {
  problem: string;
  cause: string;
  advice: string;
  actions: { label: string; approval: boolean }[];
}

export interface ReportBlock {
  title: string;
  period: string;
  metrics: { label: string; value: string; delta?: number }[];
  sections: { title: string; lines: string[] }[];
}

