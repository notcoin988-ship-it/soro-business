// Killer Demo) показывают одни и те же величины под разными углами:
// доля решённого AI видна и на дашборде руководителя, и в недельном
// отчёте, и на финальном экране демо. Стоит завести их по месту — и на
// встрече с банком дашборд покажет 77,4%, а отчёт 81,2%. Такое расхождение
// убивает доверие ко всему стенду быстрее, чем любая недоделка: цифрам
// перестают верить целиком.
//
// ДАННЫЕ ДЕТЕРМИНИРОВАННЫЕ. Никакого Math.random: демо обязано показывать
// одно и то же при каждом обновлении страницы. Презентатор репетирует
// сценарий и называет числа вслух — они не имеют права меняться между
// репетицией и встречей.
//
// ЭТО СИМУЛЯЦИЯ, И ЭТО ВИДНО. Всё, что отсюда, помечается в интерфейсе
// как оценка demo-среды (`ESTIMATED_NOTE`), а не выдаётся за выгрузку из
// АБС банка. Настоящие цифры стенда живут в `/api/overview` и
// `/api/analytics` и приходят из базы — их подменять нельзя.

/** Подпись к любому расчётному числу. Показывается рядом со значением. */
export const ESTIMATED_NOTE = "оценка · demo-среда";

/** Дробное число по-русски: разделитель — запятая.
 *
 *  Мелочь, которая бросается в глаза именно на демо: рядом стоят
 *  «77.4%» из шаблонной строки и «+8,1%» из компонента дельты, и экран
 *  сразу выглядит собранным из кусков. Один хелпер на весь файл. */
export function ru(value: number): string {
  return String(value).replace(".", ",");
}

