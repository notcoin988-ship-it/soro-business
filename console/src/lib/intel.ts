/** Ответ на бизнес-вопрос. Детерминированный подбор по ключевым словам. */
export function askBusiness(question: string): BusinessAnswer {
  const text = question.toLowerCase();
  for (const entry of ANSWERS) {
    if (entry.match.some((word) => text.includes(word))) return entry.answer;
  }
  // Вопрос не из сценария. Врать не будем: честно говорим, что данных нет,
  // и предлагаем то, на что ответить можем. Это ровно то поведение, которое
  // демо и продаёт — AI не выдумывает.
  return {
    answer:
      "На этот вопрос в данных за период нет достаточных оснований. " +
      "Могу разобрать рост обращений, темы клиентов, изменения к прошлой неделе " +
      "или нагрузку на операторов.",
    evidence: ["Вопрос не соотнесён ни с одной темой периода"],
    metrics: [],
    sources: [],
    recommendation: "Уточните вопрос или выберите подсказку ниже",
  };
}

